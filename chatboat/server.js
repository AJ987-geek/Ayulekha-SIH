/**
 * AyuLekha Healthcare AI Backend Server with TinyFish Integration (ESM)
 * Delivers immediate step-by-step health solutions & remedies without questionnaires
 */

import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import path from 'path';
import { fileURLToPath } from 'url';
import { generateAyuLekhaSolution, checkForRedFlags } from './triageEngine.js';
import { TinyFishService } from './tinyfishService.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

const tinyFish = new TinyFishService(process.env.TINYFISH_API_KEY, process.env.TINYFISH_BASE_URL);

// Middleware
app.use(cors());
app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

// In-memory active sessions
const sessions = new Map();

/**
 * Endpoint: AyuLekha Direct Solution Generator
 */
app.post('/api/chat', async (req, res) => {
  try {
    const { message, sessionId = 'default', apiKey = '', vitals = {} } = req.body;

    if (!message || message.trim().length === 0) {
      return res.status(400).json({ error: 'Message content is required.' });
    }

    if (apiKey) {
      tinyFish.setApiKey(apiKey);
    }

    // Retrieve or create session
    let session = sessions.get(sessionId) || {
      id: sessionId,
      history: [],
      chiefComplaint: message,
      lastCategory: null
    };

    // 1. Generate Direct Solution from AyuLekha Engine
    const result = generateAyuLekhaSolution(message);
    session.lastCategory = result.categoryName;

    // 2. Perform TinyFish Web Search for evidence-based real-time insights
    let webInsights = null;
    try {
      webInsights = await tinyFish.searchMedicalInfo(message, result.categoryName);
    } catch (e) {
      console.log('TinyFish lookup note:', e.message);
    }

    // Update history
    session.history.push({ role: 'user', content: message });
    session.history.push({ role: 'assistant', content: result.reply });
    sessions.set(sessionId, session);

    return res.json({
      success: true,
      sessionId,
      isEmergency: result.isEmergency,
      categoryName: result.categoryName,
      reply: result.reply,
      otcGuidance: result.otcGuidance,
      specialist: result.specialist,
      webInsights: webInsights,
      tinyFishActive: tinyFish.isConfigured()
    });
  } catch (error) {
    console.error('Chat endpoint error:', error);
    res.status(500).json({ error: 'Internal health assistant error. Please try again.' });
  }
});

/**
 * Endpoint: TinyFish Search
 */
app.post('/api/tinyfish/search', async (req, res) => {
  try {
    const { query, apiKey } = req.body;
    if (apiKey) tinyFish.setApiKey(apiKey);

    const results = await tinyFish.searchMedicalInfo(query || 'clinical guidelines and home remedies');
    res.json(results);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

/**
 * Endpoint: TinyFish Config & Test
 */
app.post('/api/tinyfish/config', async (req, res) => {
  try {
    const { apiKey } = req.body;
    if (apiKey) {
      tinyFish.setApiKey(apiKey);
      const testResult = await tinyFish.testConnection(apiKey);
      return res.json({
        success: true,
        configured: true,
        message: 'TinyFish API Key updated successfully!',
        details: testResult
      });
    } else {
      return res.json({
        success: true,
        configured: false,
        message: 'Running in built-in AyuLekha Health Solution Engine mode.'
      });
    }
  } catch (e) {
    res.status(500).json({ error: e.message });
  }
});

/**
 * Endpoint: Generate Doctor Consultation Summary (SOAP clinical note)
 */
app.post('/api/export-summary', (req, res) => {
  try {
    const { patientInfo = {}, symptoms = '', category = '', specialist = '' } = req.body;

    const summaryReport = {
      title: 'AYULEKHA HEALTHCARE SUMMARY REPORT',
      disclaimer: 'Generated by AyuLekha Health Assistant powered by TinyFish AI. This report is an informational guidance aid and does not replace a physical medical prescription.',
      timestamp: new Date().toLocaleString(),
      patientDetails: {
        age: patientInfo.age || 'Not specified',
        gender: patientInfo.gender || 'Not specified',
        preexisting: patientInfo.preexisting || 'None reported',
        painScore: patientInfo.painScore || '0/10'
      },
      chiefComplaint: symptoms || 'General health consultation',
      category: category || 'General Health Guidance',
      recommendedSpecialist: specialist || 'General Physician / Family Doctor'
    };

    res.json({ success: true, report: summaryReport });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

/**
 * Endpoint: Server Health Status
 */
app.get('/api/status', (req, res) => {
  res.json({
    status: 'online',
    aiName: 'AyuLekha',
    serverTime: new Date().toISOString(),
    tinyFishConnected: tinyFish.isConfigured(),
    features: ['Direct Step-by-Step Solutions', 'Red Flag Emergency Alert', 'TinyFish Web Agent', 'Home Remedies Protocol']
  });
});

app.listen(PORT, () => {
  console.log(`=======================================================`);
  console.log(`🌿 AyuLekha Healthcare Assistant is running!`);
  console.log(`🌐 Web App URL: http://localhost:${PORT}`);
  console.log(`⚡ TinyFish Agent: ${tinyFish.isConfigured() ? 'API Key Configured' : 'Offline Engine Ready'}`);
  console.log(`=======================================================`);
});
